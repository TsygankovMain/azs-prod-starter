// Токен-бакет для общего темпа обращений к порталу.
//
// Зачем отдельным модулем и почему общий: сегодня темпом не управляет никто —
// каждый телефон и каждый воркер гонят свои цепочки, не зная друг о друге, а
// лимит портала (2 запроса в секунду) общий. Этот объект — единственное
// место, где виден суммарный расход, поэтому экземпляр обязан быть ОДИН на
// процесс и делиться между всеми воркерами.
//
// crmSyncWorker.drain() — цикл while(worked) БЕЗ пауз в СВОЁМ теле (см. её
// заголовок) — приём, который в этом модуле копировать нельзя. С I1
// (финальное ревью ветки) сам этот факт больше не значит "мимо лимитера":
// реальные обращения к Битриксу, которые drain() в итоге вызывает
// (buildCrmSyncRunner -> syncReportCrmStrict в reportsRoutes.js), сами берут
// токен здесь перед каждым вызовом — тем же приёмом, что photoPublisher уже
// применяет для photoPublishWorker. Цикл crmSyncWorker остаётся быстрым и
// беспаузным НАМЕРЕННО — пейсинг живёт не в скорости цикла, а в реальных
// вызовах, которые он делает.
//
// acquire() последовательно сериализует ожидающих через цепочку промисов —
// НЕ потому, что без этого два конкурентных вызова могли бы оба увидеть
// «токен есть» и списать один и тот же токен дважды: между финальной
// проверкой (tokens >= 1) и списанием (tokens -= 1) внутри takeOne() нет ни
// одного await, а значит между ними в принципе не может вклиниться другой
// вызов — JS не переключает выполнение вне точек await. Списание уже
// атомарно и без очереди. Настоящая причина серилизации — СПРАВЕДЛИВОСТЬ
// порядка обслуживания: без общей очереди несколько конкурентных вызовов,
// уснувших в ожидании токена, разбудились бы в порядке, который решает
// таймер (не обязательно в порядке вызова acquire()), и более поздний
// вызов мог бы обслужиться раньше более раннего. Цепочка промисов гарантирует
// строгий FIFO — каждый следующий takeOne() не начинает выполняться, пока
// не завершится предыдущий.
//
// ---------------------------------------------------------------------------
// I2 (финальное ревью ветки, ЗАДОКУМЕНТИРОВАТЬ, НЕ чинить) — эта защита НЕ
// абсолютна, и следующему читателю не следует считать «1 acquire() = 1
// запрос к порталу» гарантией.
//
// bitrixRestClient.js: callWithTransientRetry ретраит КАЖДЫЙ вызов до 3 раз
// (RETRY_BACKOFF_MS = [800, 1600, 3200]) на transient-ошибках — список
// включает QUERY_LIMIT_EXCEEDED (см. src/shared/transientErrors.js), то есть
// ИМЕННО ту ошибку, которая уронила смены 31 июля и 3 августа. Ретраи
// происходят ВНУТРИ одного вызова client.call(...)/updateReportItem(...)/
// getCrmItem(...) — вызывающий код (publishOne, buildCrmSyncRunner и т.д.)
// берёт токен лимитера ОДИН раз перед вызовом и не видит эти скрытые
// повторы. Значит один "оплаченный" acquire() может обернуться ДО ЧЕТЫРЁХ
// реальных HTTP-запросов к порталу (1 исходный + до 3 ретраев).
//
// limiter.penalize(ms) — единственный механизм, которым лимитер узнаёт, что
// нужно затормозить СИЛЬНЕЕ обычного расписания, — вызывается вызывающим
// кодом (см. handleError в photoPublishWorker.js) ТОЛЬКО когда
// error.retryAfterMs задан, а он задаётся ТОЛЬКО когда ответ Битрикса нёс
// заголовок Retry-After (bitrixRestClient.js: retryAfterSeconds из
// retryAfterHeader). Присутствует ли Retry-After у ответа именно на
// QUERY_LIMIT_EXCEEDED — открытый вопрос спецификации портала на момент
// написания этого комментария (не подтверждено эмпирически ни в одну, ни в
// другую сторону). Если НЕ присутствует — penalize() для этой ошибки не
// сработает НИКОГДА, и единственной защитой от повторного перегруза
// остаётся штатное расписание токен-бакета (ratePerSec/burst), без
// дополнительного демпфирования именно на сигнал "портал уже сказал
// притормозить".
// ---------------------------------------------------------------------------

export const createRateLimiter = ({
  ratePerSec = 1.4,
  burst = 3,
  now = () => Date.now(),
  sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
} = {}) => {
  if (!(ratePerSec > 0)) throw new Error('ratePerSec must be positive');
  // Раунд правок 2 (найдено ревью): burst < 1 математически недостижим для
  // условия tokens>=1 в цикле takeOne() ниже — refill() не поднимает tokens
  // выше burst (Math.min), значит acquire() провисел бы навсегда, ни разу не
  // дойдя до break. Из-за сериализации через queue такое зависание не
  // локально: один застрявший acquire() молча и навсегда блокирует все
  // последующие вызовы от всех воркеров, использующих этот общий экземпляр.
  // Поэтому граница строгая: >= 1, а не > 0.
  if (!(burst >= 1)) throw new Error('burst must be at least 1');

  let tokens = burst;
  let lastRefillAt = now();
  let frozenUntil = 0;
  let queue = Promise.resolve();

  const refill = () => {
    const at = now();
    const elapsedMs = at - lastRefillAt;
    if (elapsedMs > 0) {
      tokens = Math.min(burst, tokens + (elapsedMs / 1000) * ratePerSec);
      lastRefillAt = at;
    }
  };

  const takeOne = async () => {
    // Раунд правок 1 (ревью нашло Critical): frozenUntil нельзя проверять
    // один раз при входе. Пока этот вызов спит (неважно, на ожидании токена
    // или на самой заморозке), конкурентный penalize() из другого воркера
    // может установить или продлить заморозку — и линейный проход из одного
    // if/if эту новость никогда не увидит, так как после сна сразу списывает
    // токен и возвращает управление. Поэтому — цикл, перепроверяющий обе
    // причины ждать заново после КАЖДОГО пробуждения, а не только на входе.
    //
    // Завершение гарантировано при трёх условиях:
    //  1. burst >= 1 — проверено guard'ом на входе в createRateLimiter (там
    //     же обоснование). Без этого условия tokens>=1 недостижим математически
    //     ни за какое время (потолок Math.min(burst,...) в refill() держит
    //     tokens ниже 1 вечно) — раунд правок 2 нашёл именно это: acquire()
    //     висел навсегда при burst<1, хотя пред-цикловый код (до раунда 1)
    //     на том же входе просто ошибался за один сон, но завершался.
    //  2. sleep(ms) обязана соответствовать продвижению now() минимум на ms —
    //     верно для боевых дефолтов (Date.now/setTimeout) и для тестового
    //     harness (advance(ms) внутри sleep). Если этот контракт нарушить —
    //     подставить sleep, резолвящийся без продвижения часов — freezeMs и
    //     waitMs не уменьшатся, и цикл тоже не завершится.
    //  3. Обе ветки спят только строго положительное время (guard `> 0`
    //     перед сном; waitMs — Math.ceil от строго положительной величины,
    //     значит не может дать 0) — цикл не может пустым образом вращаться
    //     на нулевых интервалах.
    // При этих трёх условиях каждая итерация реально продвигает now()
    // вперёд; при отсутствии новых penalize() каждая ветка срабатывает не
    // более одного раза подряд. Дальнейшие повторы возможны только за счёт
    // конкурентных penalize() с растущим горизонтом, прилетающих, пока этот
    // вызов уже спит; это конечное число реальных внешних событий (штрафов
    // от портала), а не дефект цикла.
    for (;;) {
      refill();

      // Штраф от портала (Retry-After) важнее накопленных токенов: продолжать
      // слать в этот момент — усиливать давление ровно тогда, когда портал
      // просит его снизить.
      const freezeMs = frozenUntil - now();
      if (freezeMs > 0) {
        await sleep(freezeMs);
        continue;
      }

      if (tokens < 1) {
        const waitMs = Math.ceil(((1 - tokens) / ratePerSec) * 1000);
        await sleep(waitMs);
        continue;
      }

      break;
    }
    tokens -= 1;
  };

  return {
    // Сериализация обязательна: параллельные acquire() без неё оба увидели бы
    // один и тот же запас и выпустили бы два запроса на один токен.
    acquire() {
      const next = queue.then(takeOne, takeOne);
      queue = next.catch(() => {});
      return next;
    },
    // Только продлевает заморозку, никогда не сокращает: более мягкий ответ
    // от другого запроса не должен отменять более строгий.
    penalize(ms) {
      const until = now() + Math.max(0, Number(ms) || 0);
      if (until > frozenUntil) frozenUntil = until;
    },
    available() {
      refill();
      return tokens;
    }
  };
};

export default createRateLimiter;
